      if ($global:proofBegins -ne 0 -or $global:proofOutcomes.Count -ne 0 -or $global:proofOperationDepth -ne 1) { throw 'Nested validation replaced caller operation' }
    } else {
      $expected = if ($refused) { 'failure' } else { 'success' }
      if ($global:proofBegins -ne 1 -or $global:proofOutcomes[0] -ne $expected -or $global:proofOperationDepth -ne 0) { throw 'Standalone validation fence/outcome false' }
    }
    if ($refused -ne ($mode -eq 'browser-failure')) { throw 'Validation failure verdict false' }
    $cases += "admitted $mode executes whole validation under one operation"
    if ($global:proofNestedParentFence) {
      if (-not $global:proofNestedParentFence.CanRead) { throw 'Nested validation closed its parent fence' }
      $global:proofNestedParentFence.Dispose()
    }
  }
  foreach ($mode in @('absent','disposed','foreign')) {
    $global:proofOperationDepth=1; $global:proofObservations=0; $global:proofBegins=0; $global:proofOutcomes=@()
