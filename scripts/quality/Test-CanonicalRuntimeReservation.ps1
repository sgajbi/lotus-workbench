    $otherFence=$null
    $validationArgs=@{ProjectsRoot=$fixtureRoot; RuntimeHolder='fixture-owner'; RuntimeOperationToken='controlled-admission'}
    if ($mode -eq 'disposed') { $global:proofNestedParentFence.Dispose(); $validationArgs.RuntimeOperationFence=$global:proofNestedParentFence }
    if ($mode -eq 'foreign') { $otherFence=[IO.File]::Open((Join-Path $fixtureRoot 'foreign-validation.lock'),'OpenOrCreate','ReadWrite','None'); $validationArgs.RuntimeOperationFence=$otherFence }
    $refused=$false
    try { & (Join-Path $repoRoot 'scripts/live/Validate-LotusFrontOfficeCanonical.ps1') @validationArgs }
    catch { if ($_.Exception.Message -notmatch 'MISSING_LIVE_PARENT_FENCE') { throw }; $refused=$true }
    finally { $global:proofNestedParentFence.Dispose(); if ($otherFence) { $otherFence.Dispose() } }
    if (-not $refused -or $global:proofObservations -or $global:proofBegins -or $global:proofOutcomes.Count) { throw 'Stale token admitted unfenced validation I/O' }
    $cases += "nested validation $mode parent fence refuses before observations"
  }
  @{contract='canonical-runtime-reservation-consumer'; evidence='controlled supplier interface, real shipped scripts'; cases=$cases; passed=$true} | ConvertTo-Json -Depth 4
} finally {
  Remove-Item Function:/docker,Function:/Get-NetTCPConnection,Function:/Get-Process,Function:/Stop-Process -ErrorAction SilentlyContinue
  # Remove only this test's resolved, generated temporary fixture.
  $resolved = (Resolve-Path -LiteralPath $fixtureRoot).Path
  $temporary = [System.IO.Path]::GetFullPath([System.IO.Path]::GetTempPath())
  if (-not $resolved.StartsWith($temporary, [System.StringComparison]::OrdinalIgnoreCase)) { throw 'Invalid fixture cleanup target' }
  Remove-Item -LiteralPath $resolved -Recurse -Force
}
